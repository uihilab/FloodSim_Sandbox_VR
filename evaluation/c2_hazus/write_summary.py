"""Writes summary.md from the analysis results. Called by analysis.py; every number is filled from results."""

import json
import os

import pandas as pd


def usd(x):
    return f"${x / 1e6:,.1f}M"


def f3(x):
    return f"{x:.3f}"


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def write(res, a_df, metr, binned, cls, c_df, cd_df, d_df, path):
    here = os.path.dirname(path)
    prov = json.load(open(os.path.join(here, "..", "data", "c2", "provenance.json"), encoding="utf-8"))
    nf = {x["county"]: x for x in prov["nfip"]}
    A = res["A"]
    P = metr.loc["Primary: both counties, replacement-cost basis"]
    S = metr.loc["Excluding 0-1 ft depths (possible feet-as-inches entries)"]
    J = metr.loc["Johnson County only (Iowa City, Coralville)"]
    acv = metr.loc["Actual-cash-value basis"]
    other = res["B_other"]
    fams = res["C_curve_families"]
    fk = [v["factor"] for v in fams.values()]
    osm = res["D_osm_coverage"]

    a_tab = a_df.assign(structure_usd=a_df["structure_usd"].map(usd), content_usd=a_df["content_usd"].map(usd),
                        total_usd=a_df["total_usd"].map(usd))

    m_cols = ["n", "mean_observed_DR", "mean_predicted_DR", "bias_pred_minus_obs", "MAE", "RMSE",
              "spearman_obs_vs_pred", "aggregate_pred_over_obs_usd"]
